def main() -> bool:
    global VERIFY
    ap = argparse.ArgumentParser(description="openSME e2e tests (SSO etc.)")
    ap.add_argument("domain", nargs="?", default=None, help="stack domain")
    ap.add_argument("--insecure", action="store_true", help="disable TLS verification")
    ap.add_argument("--map-local", action="store_true",
                    help="resolve unresolvable *.local hosts to loopback")
    ap.add_argument("--skip-flows", action="store_true", help="skip SSO flow tests")
    ap.add_argument("--skip-apps", action="store_true", help="skip app reachability")
    ap.add_argument("--idp-url", default=None, help="override IdP base URL")
    args = ap.parse_args()

    dotenv = load_env_file()

    def cfg(key, default=""):
        return os.environ.get(key) or dotenv.get(key) or default

    domain = (args.domain or cfg("OPENSME_DOMAIN", "localhost")).strip()
    localish = is_localish(domain)
    VERIFY = not (args.insecure or cfg("E2E_INSECURE") in ("1", "true", "yes") or localish)
    if not VERIFY:
        urllib3.disable_warnings()
    if localish or args.map_local:
        install_dns_fallback()

    idp_host = cfg("ZITADEL_DOMAIN", f"auth.{domain}")
    idp_base = args.idp_url or f"https://{idp_host}"
    portal_base = (
        "http://127.0.0.1:8080" if domain in ("localhost", "127.0.0.1")
        else f"https://{cfg('PORTAL_DOMAIN', f'portal.{domain}')}"
    )
    cloud_base = f"https://{cfg('OPENCLOUD_DOMAIN', f'cloud.{domain}')}"
    matrix_base = f"https://matrix.{domain}"
    notes_base = f"https://notes.{domain}"
    paperless_base = f"https://paperless.{domain}"

    session = requests.Session()
    session.verify = VERIFY

    result = Result("e2e")
    result.header(f"openSME e2e — domain={domain} idp={idp_base} verify={VERIFY}")

    if not probe(session, idp_base + "/debug/ready") and not probe(session, portal_base + "/health"):
        result.fail("stack unreachable — start it first (./scripts/demo.sh or make up)")
        return result.summary()

    # 1) IdP discovery
    disc = section_discovery(result, session, idp_base)

    # 2) Portal
    section_portal(result, session, portal_base)

    # 3-5) SSO flows
    flows_ok = bool(disc) and not args.skip_flows
    client_id, csec, owned, pat = cfg("E2E_OIDC_CLIENT_ID"), cfg("E2E_OIDC_CLIENT_SECRET"), None, None
    callback, post_logout = f"{idp_base}/e2e-callback", f"{idp_base}/e2e-loggedout"
    login_name = cfg("E2E_ZITADEL_LOGIN_NAME", "zitadel-admin")
    pw = cfg("ZITADEL_ADMIN_PASSWORD")

    lc_pat = cfg("E2E_ZITADEL_LOGINCLIENT_PAT")
    client_uid = None

    if flows_ok and not client_id:
        pat = cfg("E2E_ZITADEL_PAT") or fetch_seeded("/machinekey/pat")
        if not pat:
            result.skip("SSO flows: no machine PAT reachable (docker compose down?) — "
                        "set E2E_OIDC_CLIENT_ID or E2E_ZITADEL_PAT")
            flows_ok = False
        else:
            try:
                client_id, pid, app_id = bootstrap_app(session, idp_base, pat, callback, post_logout)
                owned = (pid, app_id)
                result.ok(f"bootstrapped throw-away OIDC app (client {client_id})")
            except E2EError as e:
                result.skip(f"SSO flows skipped — OIDC app bootstrap failed: {e}")
                flows_ok = False

    if flows_ok:
        lc_pat = lc_pat or fetch_seeded("/machinekey/login-client.pat")
        client_uid = resolve_user_id(session, idp_base, pat or lc_pat, LOGIN_CLIENT_USER) \
            if lc_pat else None
        if not lc_pat or not client_uid:
            result.skip("SSO flows: no login-client PAT (re-run `zitadel setup --steps "
                        "/steps.yaml` on a fresh DB) or set E2E_ZITADEL_LOGINCLIENT_PAT")
            flows_ok = False

    login_uid = None
    if flows_ok:
        login_uid = resolve_user_id(session, idp_base, pat or lc_pat, login_name)
        if not login_uid:
            result.fail(f"auth-code flow: login user {login_name!r} not found in IdP")
            flows_ok = False

    if flows_ok and not pw:
        result.skip("SSO flows: no admin credentials (set ZITADEL_ADMIN_PASSWORD)")
        flows_ok = False

    sess = None
    if flows_ok:
        try:
            _, sess = run_auth_code_flow(
                result, session, disc, client_id, csec, idp_base,
                lc_pat, client_uid, login_name, login_uid, pw, callback,
            )
        except E2EError as e:
            result.fail(f"auth-code flow: {e}")
            flows_ok = False

    if flows_ok and sess:
        if section_sso_reuse(result, session, disc, client_id, callback, idp_base,
                             lc_pat, client_uid, sess):
            section_logout(result, session, idp_base, lc_pat, client_uid, sess,
                           client_id, callback, disc)

    # Cleanup the throw-away app (best effort)
    if owned and pat:
        try:
            cleanup_app(session, idp_base, pat, owned[0], owned[1])
            result.ok("removed throw-away OIDC app")
        except Exception:
            result.warn("could not remove throw-away OIDC app (delete project 'e2e-sso')")

    # 6) App reachability
    if not args.skip_apps:
        section_apps(result, session, [
            ("opencloud", cloud_base + "/"),
            ("synapse", matrix_base + "/_matrix/client/versions"),
            ("notes", notes_base + "/"),
            ("paperless", paperless_base + "/"),
        ])

    # 7) Synapse SSO wiring
    if not args.skip_apps:
        section_synapse_sso(result, session, matrix_base, idp_base)

    return result.summary()


if __name__ == "__main__":
    sys.exit(0 if main() else 1)
