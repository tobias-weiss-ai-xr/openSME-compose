#!/usr/bin/env python3
"""
tests/05-e2e/run.py — Layer 5: end-to-end tests (SSO & friends).

Runs real user journeys over HTTP against a RUNNING stack (same convention
as 03-smoke, plus real credentials from .env):

  1. IdP (Zitadel)   — OIDC discovery + JWKS
  2. Portal          — landing page, /health, /api/services
  3. SSO login flow  — authorization-code + PKCE, logged in programmatically
                       through the Zitadel v2 Session API (the API the Login
                       v2 UI itself uses), using a throw-away OIDC app that
                       is bootstrapped (and removed) via the Management API
  4. Single sign-on  — a second authorize is finalized with the same IdP
                       session (no second credential check)
  5. Logout          — session termination; the dead session cannot
                       finalize further auth requests
  6. Apps            — reachability of running overlays (cloud, matrix,
                       notes, paperless)
  7. Synapse SSO     — /login/sso/redirect bounces to the IdP

No browser is involved: the login client PAT (IAM_LOGIN_CLIENT role, seeded
by `zitadel setup --steps /steps.yaml` into /machinekey/login-client.pat)
authorizes session creation, password checks and auth-request finalization.

Configuration precedence: env vars > .env > defaults. Relevant keys:
  OPENSME_DOMAIN, ZITADEL_DOMAIN, PORTAL_DOMAIN, OPENCLOUD_DOMAIN
  ZITADEL_ADMIN_PASSWORD            (demo: generated by scripts/demo.sh)
  E2E_ZITADEL_LOGIN_NAME            (default: zitadel-admin)
  E2E_ZITADEL_PAT                   machine-user PAT (skips docker compose cp)
  E2E_ZITADEL_LOGINCLIENT_PAT       login-client PAT (skips docker compose cp)
  E2E_OIDC_CLIENT_ID / _SECRET      pre-registered app (skips bootstrap)
  E2E_INSECURE=1                    force TLS verification off

Local demo domains (*.local) get two conveniences automatically:
  - unresolvable hostnames resolve to loopback (reaches local Traefik)
  - TLS verification is disabled (self-signed demo certs)

Usage:
  python3 tests/05-e2e/run.py                  # domain from .env / localhost
  python3 tests/05-e2e/run.py opensme.local
  make e2e DOMAIN=opensme.org

Exit codes: 0 = pass, 1 = one or more checks failed (skips don't fail).
"""

